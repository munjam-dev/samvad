package com.example.security

import android.content.Context
import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import java.io.File
import java.io.FileInputStream
import java.io.FileOutputStream
import java.io.InputStream
import java.security.KeyStore
import javax.crypto.Cipher
import javax.crypto.CipherInputStream
import javax.crypto.CipherOutputStream
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

class CryptoVaultManager(private val context: Context) {

    private var testFallbackKey: SecretKey? = null

    private val keyStore: KeyStore? = try {
        KeyStore.getInstance(KEYSTORE_PROVIDER).apply { load(null) }
    } catch (_: Exception) {
        null
    }

    private val vaultDirectory: File by lazy {
        File(context.filesDir, "vault").apply {
            if (!exists()) {
                mkdirs()
            }
        }
    }

    private val previewDirectory: File by lazy {
        File(context.cacheDir, "preview").apply {
            if (!exists()) {
                mkdirs()
            }
        }
    }

    private val sharedDirectory: File by lazy {
        File(context.cacheDir, "shared").apply {
            if (!exists()) {
                mkdirs()
            }
        }
    }

    init {
        getOrCreateSecretKey()
    }

    @Synchronized
    private fun getOrCreateSecretKey(): SecretKey {
        val ks = keyStore
        if (ks == null) {
            if (testFallbackKey == null) {
                val keyGen = KeyGenerator.getInstance("AES")
                keyGen.init(256)
                testFallbackKey = keyGen.generateKey()
            }
            return testFallbackKey!!
        }

        if (!ks.containsAlias(KEY_ALIAS)) {
            val keyGenerator = KeyGenerator.getInstance(
                KeyProperties.KEY_ALGORITHM_AES,
                KEYSTORE_PROVIDER
            )
            val parameterSpec = KeyGenParameterSpec.Builder(
                KEY_ALIAS,
                KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT
            )
                .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
                .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
                .setKeySize(256)
                .setRandomizedEncryptionRequired(true)
                .build()

            keyGenerator.init(parameterSpec)
            return keyGenerator.generateKey()
        }

        val entry = ks.getEntry(KEY_ALIAS, null) as KeyStore.SecretKeyEntry
        return entry.secretKey
    }

    /**
     * Encrypts data from input stream and saves directly to app-private vault storage.
     * Returns the relative filename.
     */
    fun encryptToFile(inputStream: InputStream, internalFileName: String): Long {
        val secretKey = getOrCreateSecretKey()
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.ENCRYPT_MODE, secretKey)

        val iv = cipher.iv // 12-byte IV generated by Cipher
        val targetFile = File(vaultDirectory, internalFileName)

        var totalBytesWritten: Long = 0
        FileOutputStream(targetFile).use { fos ->
            // Prepend IV length and IV
            fos.write(iv.size)
            fos.write(iv)
            totalBytesWritten += 1 + iv.size

            CipherOutputStream(fos, cipher).use { cos ->
                val buffer = ByteArray(8192)
                var bytesRead: Int
                while (inputStream.read(buffer).also { bytesRead = it } != -1) {
                    cos.write(buffer, 0, bytesRead)
                    totalBytesWritten += bytesRead
                }
                cos.flush()
            }
        }
        return targetFile.length()
    }

    /**
     * Decrypts the encrypted file into memory bytes for instant, ephemeral preview.
     */
    fun decryptToByteArray(internalFileName: String): ByteArray {
        val sourceFile = File(vaultDirectory, internalFileName)
        if (!sourceFile.exists()) {
            throw IllegalStateException("Encrypted document file does not exist on device.")
        }

        FileInputStream(sourceFile).use { fis ->
            val ivSize = fis.read()
            if (ivSize <= 0 || ivSize > 32) {
                throw IllegalStateException("Corrupt encryption header.")
            }
            val iv = ByteArray(ivSize)
            val readIv = fis.read(iv)
            if (readIv != ivSize) {
                throw IllegalStateException("Failed to read encryption IV.")
            }

            val secretKey = getOrCreateSecretKey()
            val cipher = Cipher.getInstance(TRANSFORMATION)
            val spec = GCMParameterSpec(GCM_TAG_LENGTH, iv)
            cipher.init(Cipher.DECRYPT_MODE, secretKey, spec)

            CipherInputStream(fis, cipher).use { cis ->
                return cis.readBytes()
            }
        }
    }

    /**
     * Writes decrypted content to an ephemeral cache file for PDF rendering or sharing.
     */
    fun decryptToTemporaryCacheFile(internalFileName: String, targetExtension: String, isShared: Boolean = false): File {
        val targetDir = if (isShared) sharedDirectory else previewDirectory
        val tempFile = File(targetDir, "doc_${System.currentTimeMillis()}.$targetExtension")

        val bytes = decryptToByteArray(internalFileName)
        tempFile.writeBytes(bytes)
        return tempFile
    }

    /**
     * Deletes the encrypted file from storage.
     */
    fun deleteEncryptedFile(internalFileName: String): Boolean {
        val file = File(vaultDirectory, internalFileName)
        return if (file.exists()) file.delete() else true
    }

    /**
     * Purges all encrypted files and preview caches.
     */
    fun clearEntireVault() {
        vaultDirectory.listFiles()?.forEach { it.delete() }
        previewDirectory.listFiles()?.forEach { it.delete() }
        sharedDirectory.listFiles()?.forEach { it.delete() }
    }

    /**
     * Purges temporary preview files.
     */
    fun clearPreviewCache() {
        previewDirectory.listFiles()?.forEach { it.delete() }
    }

    companion object {
        private const val KEY_ALIAS = "SanrakshaVaultKey"
        private const val KEYSTORE_PROVIDER = "AndroidKeyStore"
        private const val TRANSFORMATION = "AES/GCM/NoPadding"
        private const val GCM_TAG_LENGTH = 128
    }
}
